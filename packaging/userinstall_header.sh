#!/bin/sh
# ============================================================
#  动漫播放器（Linux）—— 用户级安装器（无需 root）
#  安装到 ~/.local/share/anime-player-linux，命令 ~/.local/bin/anime-player-linux
#  卸载：删除上述两个路径及 ~/.local/share/applications/anime-player-linux.desktop
#        和 ~/.local/share/icons/hicolor/256x256/apps/anime-player-linux.png
# ============================================================
set -eu

VERSION="@VERSION@"
PREFIX="${ANIME_PLAYER_PREFIX:-$HOME/.local/share/anime-player-linux}"
BIN_DIR="$HOME/.local/bin"
BIN="$BIN_DIR/anime-player-linux"
APPDIR="$PREFIX/app"
APPS_DIR="$HOME/.local/share/applications"
ICON_DIR="$HOME/.local/share/icons/hicolor/256x256/apps"

echo "==> 动漫播放器 v$VERSION 用户级安装"
echo "    安装目录：$APPDIR"

command -v python3 >/dev/null 2>&1 || {
    echo "!! 未找到 python3。Debian/Ubuntu：sudo apt install python3" >&2
    exit 1
}

# ---- 解包 -----------------------------------------------------------------
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
ARCHIVE_LINE="$(awk '/^__ANIME_PLAYER_PAYLOAD_BELOW__$/{print NR+1; exit}' "$0")"
if [ -z "$ARCHIVE_LINE" ]; then
    echo "!! 安装包损坏（未找到数据段）" >&2
    exit 1
fi
tail -n +"$ARCHIVE_LINE" "$0" | tar -xz -C "$WORK"

rm -rf "$APPDIR"
mkdir -p "$APPDIR"
cp -a "$WORK/app/." "$APPDIR/"

# ---- 依赖检查（缺失只警告，不阻断安装）---------------------------------
if ! python3 "$APPDIR/probe_env.py" >/dev/null 2>&1; then
    echo "!! 注意：当前 python3 缺少运行依赖（PyQt6 / requests / python-mpv / libmpv）。"
    echo "   Debian/Ubuntu 可用系统源一键补齐："
    echo "   sudo apt install python3-pyqt6 python3-pyqt6.qtsvg python3-requests python3-mpv libmpv2"
    echo "   （conda/pip 环境：pip install PyQt6 requests python-mpv，并确保 libmpv 可用）"
fi

# ---- 启动器 ---------------------------------------------------------------
mkdir -p "$BIN_DIR"
cat > "$BIN" <<EOF
#!/bin/sh
# anime-player-linux launcher (generated by user installer v$VERSION)
APPDIR="$APPDIR"
for py in python3 /usr/bin/python3; do
    if command -v "\$py" >/dev/null 2>&1 || [ -x "\$py" ]; then
        if "\$py" "\$APPDIR/probe_env.py" >/dev/null 2>&1; then
            exec "\$py" "\$APPDIR/run.py" "\$@"
        fi
    fi
done
echo "anime-player-linux: 未找到带有所需依赖的 Python（PyQt6 / requests / python-mpv / libmpv）。" >&2
echo "请安装：sudo apt install python3-pyqt6 python3-pyqt6.qtsvg python3-requests python3-mpv libmpv2" >&2
exit 1
EOF
chmod 755 "$BIN"

# ---- 桌面集成（图标 + .desktop，失败不影响使用）--------------------------
mkdir -p "$APPS_DIR" "$ICON_DIR"
cp "$WORK/icon/anime-player-linux.png" "$ICON_DIR/anime-player-linux.png" 2>/dev/null || true
sed "s|^Exec=.*|Exec=$BIN|; s|^Icon=.*|Icon=anime-player-linux|" \
    "$WORK/anime-player-linux.desktop" > "$APPS_DIR/anime-player-linux.desktop" 2>/dev/null || true
command -v update-desktop-database >/dev/null 2>&1 \
    && update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
command -v gtk-update-icon-cache >/dev/null 2>&1 \
    && gtk-update-icon-cache -q -t "$HOME/.local/share/icons/hicolor" >/dev/null 2>&1 || true

echo "==> 安装完成。启动方式："
echo "    终端：  $BIN"
echo "    或在应用菜单搜索“动漫播放器”"
case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo "    提示：$BIN_DIR 不在 PATH 中，终端启动请使用上面的完整路径。" ;;
esac
exit 0
__ANIME_PLAYER_PAYLOAD_BELOW__
